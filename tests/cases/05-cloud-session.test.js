// A session with Claude in automatic mode: the camera opens, a photo is taken every 2 s and sent with the
// instructions and the summary so far, the summary builds up, pause and resume, stop, and the saved session.
const { run, wait, until } = require("../harness");
const KEY = "sk-ant-api03-ABCDEFGHIJKLMNOP1234";
(async () => {
  const errors = [];
  process.on("unhandledRejection", (e) => errors.push("UNHANDLED " + (e && e.stack || e)));
  let { E, p } = await run({ kc: { VISIONX_ANTHROPIC_KEY: KEY } });
  p.catch((e) => errors.push("SCRIPT " + e.stack));
  await until(() => E.win() && E.win().__booted, 5000, "boot");
  console.log("A analyze with:", E.$("#engine").selectedOptions[0].textContent, "| hint:", E.text("#aiStatus"));
  E.type("#interval", "2");
  E.tap("#toggle");
  await until(() => E.log.ai.length >= 1, 5000, "first photo");
  console.log("B camera asked for:", JSON.stringify(E.log.camera[0].video.facingMode), "| tabs while running:", E.doc().body.classList.contains("sess") ? "hidden" : "shown", "| view:", E.$(".tabs [aria-selected=true]").textContent, "| live widget:", JSON.stringify(E.json(E.path.widget)).replace(/"(at|startedAt)":\d+/g, '"$1":…'));
  const r1 = E.log.ai[0];
  console.log("C request: provider", r1.provider, "| model", r1.model, "| max_tokens", r1.maxTokens, "| images", r1.images.length, r1.images[0].source.media_type, "| key header ends", r1.headers["x-api-key"].slice(-4));
  console.log("  system: task inside", r1.system.includes("USER TASK:\nCount the different people"), "| JSON reply asked", /Respond with JSON only/.test(r1.system), "| text:", r1.text.split("\n")[0]);
  await until(() => E.log.ai.length >= 3, 8000, "three photos");
  const r3 = E.log.ai[2];
  console.log("D third request carries the summary so far:", /Cumulative summary so far:\n2 different people so far\./.test(r3.text), "| and the state:", /"people":2/.test(r3.text));
  await until(() => /3 different/.test(E.text("#summary") || ""), 4000, "summary");
  console.log("E summary:", E.text("#summary"), "| by:", E.text("#summaryBy"), "| stats:", ["sPhotos", "sReq", "sTok"].map((id) => E.text("#" + id)).join(" / "), "| frames kept:", E.$$("#frames article").length + 1);
  console.log("  live tiles: now", E.text("#nowCap"), "| last", E.text("#lastCap"), "| tracked:", E.text("#state").slice(0, 40));
  E.tap("#hPause"); await wait(100);
  const n = E.log.ai.length;
  console.log("F paused:", E.text("#status"), "| Live tab label:", E.$("#tab-live").getAttribute("aria-label"));
  await wait(2500);
  console.log("  no photos while paused:", E.log.ai.length - n <= 1);
  E.tap("#hPause"); await until(() => E.log.ai.length > n + 1, 6000, "resume");
  console.log("  resumed:", E.text("#status"));
  E.tap("#hStop");
  await until(() => !E.$("#sesDetail").classList.contains("hidden"), 6000, "report");
  await wait(200);
  console.log("G stopped: camera stopped", E.log.cameraStopped > 0, "| view:", E.$(".tabs [aria-selected=true]").textContent, "| status:", E.text("#status"), "| widget:", JSON.stringify(E.json(E.path.widget)).replace(/"at":\d+/, '"at":…'));
  console.log("  report:", E.text("#sesDetail").slice(0, 220));
  const idx = E.json(E.path.index);
  const rec = E.json(E.path.sessions + "/" + idx[0].id + ".json");
  console.log("H saved: index", idx.length, "| photos", idx[0].photos, "| engine", idx[0].engine, "| preset", idx[0].preset, "| thumbnail", /^data:image\/jpeg/.test(idx[0].thumb || ""), "| record keys:", Object.keys(rec).join(","));
  const u = E.json(E.path.usage);
  console.log("I token usage: calls", u.p.anthropic.calls, "| features", Object.keys(u.p.anthropic.features).join(","), "| models", Object.keys(u.p.anthropic.models).join(","));
  console.log("  key anywhere in the page or files:", E.doc().documentElement.outerHTML.includes(KEY) || Object.values(E.files).some((v) => String(v).includes(KEY)));
  E.finish(); await p;
  ({ E, p } = await run({ files: E.files, kc: E.kc }));
  await until(() => E.win() && E.win().__booted, 5000, "boot");
  E.tap("#tab-sessions"); await wait(50);
  console.log("J reopened, Sessions tab:", E.text("#tab-sessions"), "|", E.text("#sesList .sesCard"));
  E.finish(); await p;
  const all = errors.concat(E.problems());
  console.log("errors:", all.length ? all.join(" | ") : "none", "| JS errors:", E.log.jsErrors || "none");
  process.exit(0);
})().catch((e) => { console.log("CRASH", e.stack); process.exit(1); });
